//! Builds liblouis (the `liblouis` submodule) into the extension, for the
//! document's text in braille (BRF export). As NVDA does: the library's C
//! files compiled directly, without its autotools build, widechar 32 bits.

use std::env;
use std::fs;
use std::path::PathBuf;

const SOURCES: &[&str] = &[
    "compileTranslationTable.c",
    "lou_translateString.c",
    "lou_backTranslateString.c",
    "logging.c",
    "pattern.c",
    "commonTranslationFunctions.c",
    "metadata.c",
    "utils.c",
];

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../liblouis");
    let sources = root.join("liblouis");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());

    let header = fs::read_to_string(sources.join("liblouis.h.in")).expect("the liblouis submodule is not initialized");
    fs::write(out.join("liblouis.h"), header.replace("@WIDECHAR_TYPE@", "unsigned int")).unwrap();
    // The autotools build generates config.h; all it needs is defined below.
    fs::write(out.join("config.h"), "/* Generated by build.rs: the settings are -D flags. */\n").unwrap();
    let configure = fs::read_to_string(root.join("configure.ac")).unwrap();
    let version = configure
        .lines()
        .find_map(|line| line.strip_prefix("AC_INIT([Liblouis], ["))
        .and_then(|rest| rest.split(']').next())
        .expect("no AC_INIT version in liblouis/configure.ac");

    let mut build = cc::Build::new();
    build
        .include(&out)
        .include(&sources)
        .define("WIDECHARS_ARE_UCS4", None)
        .define("PACKAGE_VERSION", format!("\"{version}\"").as_str())
        // Tables are always given by their full path: no built-in search directory.
        .define("TABLESDIR", "\"\"")
        .warnings(false);
    if env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        // MSVC cannot build liblouis's C99; NVDA builds it with clang-cl.
        build.compiler("clang-cl").define("_CRT_NONSTDC_NO_DEPRECATE", None);
    }
    for file in SOURCES {
        build.file(sources.join(file));
        println!("cargo:rerun-if-changed={}", sources.join(file).display());
    }
    build.compile("louis");
    println!("cargo:rerun-if-changed={}", sources.join("liblouis.h.in").display());
    println!("cargo:rerun-if-changed={}", root.join("configure.ac").display());
}
